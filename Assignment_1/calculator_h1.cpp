#include <iostream>
using namespace std;
 
int main() {
    int N;
    cout << "Enter the first number: " << endl;
    cin >> N;
    int M;
    cout << "Enter the second number: " << endl;
    cin >> M;

    cout << N << " +" << M << " = " << N + M << endl;
    cout << N << " - " << M << " = " << N - M << endl;
    cout << N << " * " << M << " = " << N * M << endl;
    cout << N << " / " << M << " = " << N / M << endl;
    cout << N << " % " << M << " = " << N % M << endl;

    return 0;
    
}